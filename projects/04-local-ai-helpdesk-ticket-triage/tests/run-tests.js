const assert = require('assert');
const r = require('../scripts/rules');
const ticket = { email:'A@example.test', subject:' Login ', description:' Cannot sign in ', idempotencyKey:'demo-1' };
const c = { category:'technical', priority:'P4', summary:'Login failure', sentiment:'negative', assigned_queue:'technical_support', confidence:.9, needs_human_review:false, reason:'Login problem', safety_or_security_concern:'none' };
let passed = 0; const ok = fn => { fn(); passed++; };
ok(() => assert.equal(r.validateTicket(ticket).email, 'a@example.test'));
ok(() => assert.throws(() => r.validateTicket({...ticket,subject:''}), /empty_subject/));
ok(() => assert.throws(() => r.validateTicket({...ticket,email:'bad'}), /invalid_email/));
ok(() => assert.equal(r.idempotency(ticket), r.idempotency(ticket)));
ok(() => assert.notEqual(r.idempotency(ticket), r.idempotency({...ticket,idempotencyKey:'different'})));
ok(() => assert.deepEqual(r.validateClassification(c), c));
ok(() => assert.throws(() => r.validateClassification({...c,category:'bad'}), /invalid_enum/));
ok(() => assert.throws(() => r.validateClassification({...c,confidence:1.1}), /invalid_confidence/));
ok(() => assert.equal(r.route(c,'active account takeover').priority, 'P1'));
ok(() => assert.equal(r.route(c,'active account takeover').assigned_queue, 'security_response'));
ok(() => assert.equal(r.route({...c,confidence:.2},'login').needs_human_review, true));
ok(() => assert.equal(r.route({...c,category:'unknown'},'unclear').assigned_queue, 'manual_review'));
ok(() => assert.deepEqual([1,2,3].map(r.retryDelaySeconds), [30,120,600]));
ok(() => assert.throws(() => r.retryDelaySeconds(4), /invalid_attempt/));
ok(() => assert.equal(r.slaDeadline('P1','2026-09-18T00:00:00Z').toISOString(), '2026-09-18T04:00:00.000Z'));
ok(() => assert.equal(r.slaDeadline('P2','2026-09-18T08:00:00Z').toISOString(), '2026-09-21T08:00:00.000Z'));
ok(() => assert.equal(r.slaDeadline('P2','2026-09-18T09:00:00Z').toISOString(), '2026-09-21T09:00:00.000Z'));
ok(() => assert.equal(r.slaDeadline('P2','2026-09-20T04:00:00Z').toISOString(), '2026-09-21T09:00:00.000Z'));
ok(() => assert.equal(r.slaDeadline('P3','2026-09-18T08:00:00Z').toISOString(), '2026-09-22T08:00:00.000Z'));
ok(() => assert.equal(r.slaDeadline('P1','2026-09-20T08:00:00Z').toISOString(), '2026-09-20T12:00:00.000Z'));
ok(() => assert.throws(() => r.slaDeadline('P5','2026-09-18T00:00:00Z'), /invalid_priority/));
ok(() => assert.throws(() => r.slaDeadline('P2','not-a-date'), /invalid_received_at/));
console.log(passed + ' deterministic tests passed');
