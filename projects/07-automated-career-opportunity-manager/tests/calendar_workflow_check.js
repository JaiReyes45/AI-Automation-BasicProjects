const fs = require('node:fs');
const assert = require('node:assert/strict');
const w = JSON.parse(fs.readFileSync('workflows/09-calendar-meetings.json', 'utf8'));
const prepare = w.nodes.find(n => n.name === 'Prepare calendar write').parameters.jsCode;
const outcome = w.nodes.find(n => n.name === 'Meeting outcome').parameters.jsCode;
const plan = {id:'action',lease:'lease',event_id:'abc123',event_version:2,private_hold:true,status:'tentative',start:'2026-11-02T10:00:00+08:00',end:'2026-11-02T10:30:00+08:00',title:'Interview',attendees:[]};
const run = (response,p=plan) => new Function('$json','$',prepare)(response,()=>({item:{json:p}})).json;
let p=run({statusCode:404});
assert.equal(p.method,'POST'); assert.equal(p.should_write,true); assert.ok(!p.payload.attendees);
assert.equal(p.send_updates,'none'); assert.equal(p.payload.status,'tentative');
const existing={id:'abc123',etag:'"etag"',extendedProperties:{private:{careerflow_event:'abc123',careerflow_revision:'1'}}};
p=run({statusCode:200,body:existing});
assert.equal(p.method,'PATCH'); assert.equal(p.etag,'"etag"');
assert.equal(run({statusCode:200,body:{...existing,attendees:[{email:'hr@example.test'}]}}).should_write,false);
assert.equal(run({statusCode:200,body:{...existing,extendedProperties:{private:{careerflow_event:'abc123',careerflow_revision:'3'}}}}).should_write,false);
assert.equal(run({statusCode:500}).should_write,false);
assert.equal(run({statusCode:404},{...plan,status:'cancelled'}).ok,true);
assert.equal(run({statusCode:200,body:{id:'abc123'}}).should_write,false);
const completed={...existing,status:'tentative',start:{dateTime:plan.start},end:{dateTime:plan.end},extendedProperties:{private:{careerflow_event:'abc123',careerflow_revision:'2'}}};
const finish=b=>new Function('$json','$',outcome)({statusCode:200,body:b},()=>({item:{json:plan}})).json;
assert.equal(finish(completed).ok,true);
assert.equal(finish({...completed,status:'confirmed'}).ok,false);
assert.equal(finish({...completed,attendees:[{email:'hr@example.test'}]}).ok,false);
console.log('PASS: private upserts, ownership/guest/revision guards, conditional updates and exact readback.');
