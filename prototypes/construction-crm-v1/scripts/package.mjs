export function packageSource(root=resolve(fileURLToPath(new URL('..',import.meta.url))),{directory:requestedDirectory}={}){
 root=realpathSync(root);
 const files=SOURCE_FILES.map(path=>{
  const source=resolve(root,path);const actual=realpathSync(source);
  if(lstatSync(source).isSymbolicLink()||!lstatSync(source).isFile()||relative(root,actual).startsWith(`..${sep}`)||relative(root,actual)==='..')throw new Error(`Unsafe release source: ${path}`);
  const bytes=readFileSync(source);return {path,bytes,sha256:createHash('sha256').update(bytes).digest('hex')};
 });
 const directory=resolve(root,requestedDirectory??'.scratch/release/source');const outputRelative=relative(resolve(root,'.scratch/release'),directory);if(outputRelative==='..'||outputRelative.startsWith('..'+sep)||outputRelative==='')throw new Error('Release output must be a new directory within .scratch/release');
 let ancestor=root;for(const segment of relative(root,dirname(directory)).split(sep)){ancestor=resolve(ancestor,segment);if(existsSync(ancestor)&&lstatSync(ancestor).isSymbolicLink())throw new Error('Unsafe release output directory link');}
 mkdirSync(dirname(directory),{recursive:true});mkdirSync(directory); // Existing releases are never deleted or overwritten.
 for(const file of files){const target=resolve(directory,file.path);mkdirSync(dirname(target),{recursive:true});writeFileSync(target,file.bytes,{flag:'wx'});}
 const manifest={format:1,algorithm:'sha256',files:files.map(({path,bytes,sha256})=>({path,bytes:bytes.length,sha256}))};
 writeFileSync(resolve(directory,'manifest.json'),JSON.stringify(manifest,null,2)+'\n',{flag:'wx'});
 return {directory,manifest};
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){try{const out=process.argv.indexOf('--out');const result=packageSource(undefined,out>=0?{directory:process.argv[out+1]}:{});console.log(JSON.stringify({directory:result.directory,fileCount:result.manifest.files.length,manifest:'manifest.json'},null,2));}catch(error){console.error(error.code==='EEXIST'?'Release already exists; review or move .scratch/release/source before packaging again.':`Packaging failed: ${error.message}`);process.exitCode=1;}}
